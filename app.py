import streamlit as st

# ตั้งค่าหน้าเว็บ
st.set_page_title(
    "ระบบช่วยเขียนบันทึกข้อความราชการอัจฉริยะ", page_icon="📝", layout="wide"
)

st.title("📝 ระบบช่วยเขียนบันทึกข้อความราชการ (ด้วยหลักการสารบรรณ)")
st.markdown(
    "ช่วยสังเคราะห์ ภาคเหตุ, ภาคความประสงค์ และภาคสรุป อัตโนมัติ"
    " ตามระเบียบงานสารบรรณ"
)

# แบ่งสัดส่วนหน้าจอ
col1, col2 = st.columns([1, 1])

with col1:
  st.markdown("### 📥 1. ข้อมูลนำเข้า (Input)")

  # เมนูอัปโหลดหนังสือต้นเรื่อง
  uploaded_file = st.file_uploader(
      "อัปโหลดหนังสือต้นเรื่อง (PDF, Word หรือ Text)", type=["pdf", "docx", "txt"]
  )

  source_text_input = st.text_area(
      "หรือคัดลอก (Copy) เนื้อหาหนังสือต้นเรื่องมาวางที่นี่:",
      placeholder="เช่น เนื้อหาจากหนังสือที่หน่วยงานอื่นส่งมาขอความอนุเคราะห์...",
      height=150,
  )

  purpose_input = st.text_area(
      "ความต้องการในการตอบกลับ / แนวทางการสั่งการ:",
      placeholder=(
          "เช่น เห็นควรอนุมัติ / มอบหมายให้ นาย ก. ดำเนินการ / ตอบปฏิเสธเพราะ..."
      ),
      height=120,
  )

  st.markdown("#### 📋 ข้อมูลส่วนหัวหนังสือ")
  org_name = st.text_input(
      "ส่วนราชการ (เจ้าของเรื่อง):", "กลุ่มงาน... สำนักงาน..."
  )
  doc_number = st.text_input("ที่หนังสือ:", "ศธ 04338/...")
  doc_subject = st.text_input("เรื่อง:", "ขออนุมัติ...")
  doc_to = st.text_input("เรียน (ผู้รับ):", "อธิการบดี / ผู้อำนวยการ...")

  generate_btn = st.button(
      "✨ สังเคราะห์และร่างบันทึกข้อความ",
      type="primary",
      use_container_width=True,
  )

with col2:
  st.markdown("### 📤 2. ร่างบันทึกข้อความ (Output)")

  if generate_btn:
    if not source_text_input and not uploaded_file:
      st.warning("⚠️ กรุณากรอกหรืออัปโหลดเนื้อหาหนังสือต้นเรื่องก่อนครับ")
    else:
      with st.spinner("กำลังวิเคราะห์และเรียบเรียงตามหลักการสารบรรณ..."):
        # จำลองการประมวลผลตามหลักการเขียนราชการ
        # (ในขั้นตอนการเชื่อมต่อ AI จริง คุณสามารถนำ Prompt กฎระเบียบสารบรรณมาใส่ตรงนี้ได้เลย)

        draft_result = f"""บันทึกข้อความ

**ส่วนราชการ:** {org_name} **โทร.** 0-2xxx-xxxx
**ที่:** {doc_number} **วันที่:** (ใส่วันที่ปัจจุบัน)
**เรื่อง:** {doc_subject}

**เรียน** {doc_to}

**๑. ภาคเหตุ** 
ตามหนังสือต้นเรื่องที่อ้างถึง/แนบมาพร้อมนี้ สรุปสาระสำคัญได้ว่า หน่วยงาน... ได้มีหนังสือขอความอนุเคราะห์... ลงวันที่... ซึ่งมีความประสงค์... 

**๒. ภาคความประสงค์** 
ในการนี้ {purpose_input} จึงเรียนมาเพื่อพิจารณาดำเนินการในส่วนที่เกี่ยวข้องต่อไป

**๓. ภาคสรุป** 
จึงเรียนมาเพื่อโปรดพิจารณา


(ลงชื่อ).......................................................
((พิมพ์ชื่อเต็ม))
ตำแหน่ง..."""

        st.success("สร้างร่างหนังสือสำเร็จ!")
        st.code(draft_result, language="markdown")

        st.download_button(
            label="📥 ดาวน์โหลดร่างบันทึกข้อความ (.txt)",
            data=draft_result,
            file_name="official_memo_draft.txt",
            mime="text/plain",
        )
  else:
    st.info(
        "💡 กรอกข้อมูลด้านซ้ายแล้วกดปุ่ม 'สังเคราะห์และร่างบันทึกข้อความ' เพื่อดูผลลัพธ์"
    )